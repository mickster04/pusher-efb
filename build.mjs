// Concatenates src/*.js (filename order) into the single file the EFB loads.
// No dependencies. Output: PackageSources/PusherSpikes/PusherSpikes.js
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const srcDir = join(root, 'src');
const out = join(root, 'PackageSources', 'PusherSpikes', 'PusherSpikes.js');

const css = readFileSync(join(srcDir, 'styles.css'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .trim();

const files = readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort();

const parts = [
  '/* Pusher Spikes - MSFS 2024 EFB feasibility app. Generated by build.mjs from src/*.js. Do not edit. */',
  '(function () {',
  "'use strict';",
  'var PS = {};',
  'PS.CSS = ' + JSON.stringify(css) + ';',
];
for (const f of files) {
  parts.push('/* ---- ' + f + ' ---- */');
  parts.push(readFileSync(join(srcDir, f), 'utf8'));
}
parts.push("if (typeof module !== 'undefined' && module.exports) { module.exports = PS; }");
parts.push('})();');

writeFileSync(out, parts.join('\n') + '\n');
console.log('built', out, '(' + files.length + ' modules)');
